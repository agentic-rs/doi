import { spawn } from 'node:child_process';
import { constants, accessSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { delimiter, dirname, join, resolve } from 'node:path';
import { constants as os_constants } from 'node:os';
import { fileURLToPath } from 'node:url';

const project_root = fileURLToPath(new URL('../', import.meta.url));
const environment_line = '. "${PROJECT_DIR:?}/.tauri/xcode-env.sh"';

function findToolDirectory(name: string, search_path: string): string {
  for (const directory of search_path.split(delimiter).filter(Boolean)) {
    try {
      accessSync(join(directory, name), constants.X_OK);
      // Resolve the directory, not cargo/pnpm's symlink to rustup/a .cjs file.
      return realpathSync(directory);
    } catch {
      // Continue searching the active terminal's toolchain.
    }
  }
  throw new Error(`${name} is unavailable. Run this command from a terminal with Node, pnpm, and Rust installed.`);
}

export function getToolDirectories(search_path = process.env.PATH ?? ''): string[] {
  return [...new Set([
    dirname(realpathSync(process.execPath)),
    ...['pnpm', 'cargo', 'rustc'].map((name) => findToolDirectory(name, search_path)),
  ])];
}

export function createEnvironmentScript(tool_directories: string[]): string {
  const tool_path = tool_directories.join(delimiter).replaceAll("'", "'\\''");
  return `# Generated by pnpm ios:open / ios:init; host paths stay out of Git.\nexport PATH='${tool_path}':"$PATH"\n`;
}

export function prepareXcodeProject(apple_directory: string, tool_directories: string[]): void {
  const project_file = join(apple_directory, 'papertrail.xcodeproj', 'project.pbxproj');
  const template_file = join(apple_directory, 'project.yml');
  let project: string;
  let template: string;
  try {
    project = readFileSync(project_file, 'utf8');
    template = readFileSync(template_file, 'utf8');
  } catch {
    throw new Error('The generated iOS project is missing. Run pnpm ios:init first.');
  }

  let phase_count = 0;
  let script_count = 0;
  project = project.replace(/\/\* Build Rust Code \*\/ = \{[\s\S]*?\n\s*\};/g, (phase) => {
    phase_count += 1;
    return phase.replace(/shellScript = ("(?:\\.|[^"\\])*");/, (_, encoded_script: string) => {
      script_count += 1;
      const script = JSON.parse(encoded_script) as string;
      if (!script.includes('ios xcode-script')) {
        throw new Error('The Xcode Rust build phase has changed; its script was left intact.');
      }
      const original = script.split('\n').filter((line) => line !== environment_line).join('\n');
      return `shellScript = ${JSON.stringify(`${environment_line}\n${original}`)};`;
    });
  });
  if (phase_count !== 1 || script_count !== 1) {
    throw new Error('Expected one Xcode Rust build phase; the generated project was left intact.');
  }

  // Preserve the same environment hook if XcodeGen regenerates the project later.
  template = template.split('\n').filter((line) => line.trim() !== environment_line).join('\n');
  template = template.replace(/^([ \t]*)- script: ([^\n]*\bios xcode-script\b[^\n]*)$/gm, (_, indent: string, command: string) => {
    return `${indent}- script: |\n${indent}    ${command}`;
  });
  let template_count = 0;
  template = template.replace(/^([ \t]*)([^\n]*\bios xcode-script\b[^\n]*)$/gm, (_, indent: string, command: string) => {
    template_count += 1;
    return `${indent}${environment_line}\n${indent}${command}`;
  });
  if (template_count !== 1) {
    throw new Error('Expected one XcodeGen Rust build script; the generated project was left intact.');
  }

  const environment_directory = join(apple_directory, '.tauri');
  mkdirSync(environment_directory, { recursive: true });
  writeFileSync(join(environment_directory, 'xcode-env.sh'), createEnvironmentScript(tool_directories), { mode: 0o600 });
  writeFileSync(project_file, project);
  writeFileSync(template_file, template);
}

class TauriCommandError extends Error {
  readonly exit_code: number;

  constructor(code: number | null, signal: NodeJS.Signals | null) {
    super(signal ? `Tauri stopped (${signal}).` : `Tauri exited with status ${code}.`);
    this.exit_code = code ?? (signal ? 128 + os_constants.signals[signal] : 1);
  }
}

async function runTauri(args: string[], tool_directories: string[]): Promise<void> {
  const child = spawn('pnpm', ['tauri', 'ios', ...args], {
    cwd: project_root,
    stdio: 'inherit',
    env: { ...process.env, PATH: [...tool_directories, process.env.PATH ?? ''].join(delimiter) },
  });
  const interrupt = () => child.kill('SIGINT');
  const terminate = () => child.kill('SIGTERM');
  process.on('SIGINT', interrupt);
  process.on('SIGTERM', terminate);
  try {
    await new Promise<void>((resolve_child, reject) => {
      child.once('error', reject);
      child.once('exit', (code, signal) => {
        if (code === 0) resolve_child();
        else reject(new TauriCommandError(code, signal));
      });
    });
  } finally {
    process.off('SIGINT', interrupt);
    process.off('SIGTERM', terminate);
  }
}

async function main(): Promise<void> {
  if (process.platform !== 'darwin') throw new Error('Xcode requires macOS.');
  const [command, ...args] = process.argv.slice(2);
  if (!['init', 'open', 'prepare'].includes(command)) {
    throw new Error('Usage: node scripts/ios-xcode.ts init|open|prepare');
  }
  const tool_directories = getToolDirectories();
  if (command === 'init') await runTauri(['init', ...args], tool_directories);
  prepareXcodeProject(join(project_root, 'src-tauri', 'gen', 'apple'), tool_directories);
  console.info('Prepared the local Xcode toolchain environment.');
  if (command === 'open') {
    console.info('Keep this terminal running while building in Xcode. Press Ctrl+C when finished.');
    await runTauri(['build', '--debug', '--open', ...args], tool_directories);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = error instanceof TauriCommandError ? error.exit_code : 1;
  });
}
